"""Generate md_system_builder/protein_templates.py from the Amber ff14SB residue library.

    python tools/generate_protein_templates.py <path to amber_ff14sb.json>

The JSON is the one in the Force Field Builder plugin
(force_field_builder/data/amber_ff14sb.json, made from AmberTools' public-domain ff14SB
files). Only what protein preparation needs is kept: atom names and elements, bonds,
the head/tail atoms, template coordinates and the residue's net charge.
"""

from __future__ import annotations

import json
import os
import sys

OUT = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "md_system_builder",
    "protein_templates.py",
)
SYMBOLS = {1: "H", 6: "C", 7: "N", 8: "O", 16: "S"}


def main(path):
    with open(path, encoding="utf-8") as fh:
        residues = json.load(fh)["residues"]
    lines = [
        '"""Amber ff14SB residue templates for protein preparation.',
        "",
        "Generated by tools/generate_protein_templates.py from AmberTools' ff14SB residue",
        "libraries (amino12.lib, aminont12.lib, aminoct12.lib; in the public domain). Do not",
        "edit by hand.",
        "",
        "name -> (atoms [(name, element)], bonds [(i, j)], head, tail, positions [(x, y, z)],",
        "net charge)",
        '"""',
        "",
        "# fmt: off",
        "TEMPLATES = {",
    ]
    for name, res in residues.items():
        atoms = [(a[0], SYMBOLS[a[2]]) for a in res["atoms"]]
        charge = round(sum(a[3] for a in res["atoms"]))
        bonds = [tuple(b) for b in res["bonds"]]
        positions = [tuple(p) for p in res["positions"]]
        lines.append(
            f"    {name!r}: ({atoms!r}, {bonds!r}, {res['head']!r}, {res['tail']!r}, "
            f"{positions!r}, {charge}),"
        )
    lines += ["}", "# fmt: on", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print(f"{OUT}: {len(residues)} templates, {os.path.getsize(OUT)} bytes")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
